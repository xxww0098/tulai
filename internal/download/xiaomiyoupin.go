const (
	xiaomiYoupinMaxBody      = 4 << 20
	xiaomiYoupinMaxResponses = 16
	xiaomiYoupinMaxImages    = 5000
)

var xiaomiYoupinNumber = regexp.MustCompile(`^[1-9][0-9]{0,19}$`)

func xiaomiYoupinID(u *url.URL) string {
	if u == nil || u.User != nil || (u.Scheme != "http" && u.Scheme != "https") ||
		(u.Port() != "" && !(u.Scheme == "https" && u.Port() == "443") && !(u.Scheme == "http" && u.Port() == "80")) ||
		(!strings.EqualFold(u.Hostname(), "www.xiaomiyoupin.com") && !strings.EqualFold(u.Hostname(), "m.xiaomiyoupin.com")) ||
		u.Path != "/detail" || strings.Contains(strings.ToLower(u.EscapedPath()), "%2f") {
		return ""
	}
	q, err := url.ParseQuery(u.RawQuery)
	if err != nil || len(q["gid"]) != 1 || !xiaomiYoupinNumber.MatchString(q.Get("gid")) {
		return ""
	}
	return q.Get("gid")
}
func isXiaomiYoupinProduct(u *url.URL) bool { return xiaomiYoupinID(u) != "" }

func xiaomiYoupinPageState(expected, current, title string) error {
	if current != expected {
		return errors.New("采集期间小米有品页面已更改")
	}
	for _, word := range []string{"安全验证", "访问受限", "请登录"} {
		if strings.Contains(title, word) {
			return errors.New("小米有品页面需要登录或安全验证，请在下载浏览器中完成")
		}
	}
	return nil
}

// Static mode cannot reproduce the browser-generated gateway request safely.
func discoverXiaomiYoupin(ctx context.Context, getter Getter, page *url.URL) (Discovery, error) {
	result := Discovery{IsPage: true}
	if err := ctx.Err(); err != nil {
		return result, err
	}
	if getter == nil || !isXiaomiYoupinProduct(page) {
		return result, errors.New("小米有品商品地址或下载客户端无效")
	}
	return result, errors.New("小米有品商品数据由网页加载，请在下载浏览器打开商品并采集")
}
func xiaomiYoupinAPI(raw string, page *url.URL) bool {
	if len(raw) == 0 || len(raw) > 8192 {
		return false
	}
	u, err := url.Parse(raw)
	return err == nil && u.User == nil && u.Scheme == "https" && sameOrigin(page, u) && u.Path == "/api/gateway/detail" &&
		u.RawQuery == "" && u.Fragment == "" && !strings.Contains(strings.ToLower(u.EscapedPath()), "%2f")
}
func xiaomiYoupinAsset(raw string) (string, bool) {
	if len(raw) == 0 || len(raw) > 8192 {
		return "", false
	}
	u, err := url.Parse(raw)
	if err != nil || u.User != nil || u.Scheme != "https" || !strings.EqualFold(u.Hostname(), "img.youpin.mi-img.com") ||
		(u.Port() != "" && u.Port() != "443") || u.Fragment != "" || path.Clean(u.Path) != u.Path || strings.Contains(u.Path, "\\") ||
		strings.Contains(strings.ToLower(u.EscapedPath()), "%2f") || (!strings.HasPrefix(u.Path, "/shop-fe/") && !strings.HasPrefix(u.Path, "/shopmain/")) {
		return "", false
	}
	switch strings.ToLower(path.Ext(u.Path)) {
	case ".jpg", ".jpeg", ".png", ".webp":
	default:
		return "", false
	}
	q, err := url.ParseQuery(u.RawQuery)
	if err != nil {
		return "", false
	}
	for k, v := range q {
		if (k != "w" && k != "h") || len(v) != 1 {
			return "", false
		}
		n, e := strconv.Atoi(v[0])
		if e != nil || n < 1 || n > 100000 || strconv.Itoa(n) != v[0] {
			return "", false
		}
	}
	return u.String(), true
}

type xiaomiYoupinResponseData struct {
	Code *int `json:"code"`
	Data struct {
		GID   json.Number `json:"gid"`
		Goods *struct {
			ShareInfo   json.RawMessage `json:"shareInfo"`
			Carousel    json.RawMessage `json:"carouselMapList"`
			ProductInfo json.RawMessage `json:"productInfo"`
			GoodsInfo   json.RawMessage `json:"goodsInfo"`
		} `json:"goods"`
	} `json:"data"`
}

// Interpret only the response generated by the site; never evaluate its code.
func xiaomiYoupinDetail(ctx context.Context, page *url.URL, body []byte) (Discovery, error) {
	result := Discovery{IsPage: true}
	id := xiaomiYoupinID(page)
	if err := ctx.Err(); err != nil {
		return result, err
	}
	if id == "" || len(body) == 0 || len(body) > xiaomiYoupinMaxBody {
		return result, errors.New("小米有品商品响应无效")
	}
	var data xiaomiYoupinResponseData
	if json.Unmarshal(body, &data) != nil || data.Code == nil || *data.Code != 0 || data.Data.Goods == nil {
		return result, errors.New("小米有品商品数据不可用，可能需要登录或验证")
	}
	if data.Data.GID.String() != id {
		return result, errors.New("小米有品商品编号与页面不匹配")
	}
	goods := data.Data.Goods
	partial := false
	var share struct {
		Poster struct {
			Title string `json:"title"`
		} `json:"poster"`
	}
	if json.Unmarshal(goods.ShareInfo, &share) == nil {
		result.Title = share.Poster.Title
	}
	seen := map[string]bool{}
	add := func(raw, kind, label string) {
		if raw == "" {
			partial = true
			return
		}
		image, ok := xiaomiYoupinAsset(raw)
		if !ok {
			partial = true
			return
		}
		if seen[image] {
			return
		}
		seen[image] = true
		if len(result.Items) >= xiaomiYoupinMaxImages {
			partial = true
			return
		}
		item := Item{URL: image, RequireImage: true, PublicOnly: true, Metadata: map[string]string{"xiaomiyoupin_gid": id, "xiaomiyoupin_kind": kind}}
		if label != "" {
			item.Metadata["xiaomiyoupin_label"] = label
		}
		if r := imageReferer(page.Scheme+"://"+page.Host+"/", image); r != "" {
			item.Headers = map[string]string{"Referer": r}
		}
		result.Items = append(result.Items, item)
	}
	var carousel []json.RawMessage
	if json.Unmarshal(goods.Carousel, &carousel) != nil || carousel == nil {
		partial = true
	}
	for _, raw := range carousel {
		if err := ctx.Err(); err != nil {
			return result, err
		}
		var v struct {
			Type *int   `json:"type"`
			URL  string `json:"url"`
		}
		if json.Unmarshal(raw, &v) != nil || v.Type == nil {
			partial = true
			continue
		}
		if *v.Type == 0 {
			add(v.URL, "main", "")
		}
	}
	var products map[string]json.RawMessage
	if json.Unmarshal(goods.ProductInfo, &products) != nil || products == nil {
		partial = true
	}
	keys := make([]string, 0, len(products))
	for k := range products {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		if err := ctx.Err(); err != nil {
			return result, err
		}
		var v struct {
			GID   json.Number `json:"gid"`
			PID   json.Number `json:"pid"`
			Name  string      `json:"name"`
			Image string      `json:"img"`
		}
		if json.Unmarshal(products[k], &v) != nil || !xiaomiYoupinNumber.MatchString(k) || v.PID.String() != k || v.GID.String() != id {
			partial = true
			continue
		}
		add(v.Image, "sku", v.Name)
	}
	var info struct {
		Intro []json.RawMessage `json:"introExt"`
	}
	if json.Unmarshal(goods.GoodsInfo, &info) != nil || info.Intro == nil {
		partial = true
	} else {
		for _, rawGroup := range info.Intro {
			if err := ctx.Err(); err != nil {
				return result, err
			}
			var group struct {
				Title  string            `json:"title"`
				Images []json.RawMessage `json:"imagesArray"`
			}
			if json.Unmarshal(rawGroup, &group) != nil || group.Images == nil {
				partial = true
				continue
			}
			for _, raw := range group.Images {
				if err := ctx.Err(); err != nil {
					return result, err
				}
				var image string
				if json.Unmarshal(raw, &image) != nil {
					partial = true
					continue
				}
				add(image, "detail", group.Title)
			}
		}
	}
	if len(result.Items) == 0 {
		return result, errors.New("小米有品当前商品未返回可确认的图片")
	}
	if partial {
		return result, errors.New("小米有品部分图片或商品数据无法确认，已保留可确认的图片")
	}
	return result, nil
}

type xiaomiYoupinObserved struct {
	requestID network.RequestID
	failed    bool
}
type xiaomiYoupinObserver struct {
	page           *url.URL
	done           <-chan struct{}
	events         chan xiaomiYoupinObserved
	mu             sync.Mutex
	pending, ready map[network.RequestID]bool
	count          atomic.Int32
	overflow       atomic.Bool
}

func newXiaomiYoupinObserver(page *url.URL, done <-chan struct{}) *xiaomiYoupinObserver {
	return &xiaomiYoupinObserver{page: page, done: done, events: make(chan xiaomiYoupinObserved, xiaomiYoupinMaxResponses), pending: map[network.RequestID]bool{}, ready: map[network.RequestID]bool{}}
}
func (o *xiaomiYoupinObserver) send(v xiaomiYoupinObserved) {
	select {
	case o.events <- v:
	case <-o.done:
	default:
		o.overflow.Store(true)
	}
}
func (o *xiaomiYoupinObserver) event(event any) {
	switch e := event.(type) {
	case *network.EventRequestWillBeSent:
		if e.RedirectResponse != nil {
			o.mu.Lock()
			ok := o.pending[e.RequestID]
			delete(o.pending, e.RequestID)
			delete(o.ready, e.RequestID)
			o.mu.Unlock()
			if ok {
				o.send(xiaomiYoupinObserved{requestID: e.RequestID, failed: true})
			}
			return
		}
		if e.Request == nil || e.Request.Method != "POST" || !xiaomiYoupinAPI(e.Request.URL, o.page) {
			return
		}
		if o.count.Add(1) > xiaomiYoupinMaxResponses {
			o.overflow.Store(true)
			return
		}
		o.mu.Lock()
		o.pending[e.RequestID] = true
		o.mu.Unlock()
	case *network.EventResponseReceived:
		o.mu.Lock()
		ok := o.pending[e.RequestID]
		if ok && (e.Response == nil || e.Response.Status != 200 || e.Response.FromServiceWorker ||
			(e.Type != network.ResourceTypeXHR && e.Type != network.ResourceTypeFetch) || !xiaomiYoupinAPI(e.Response.URL, o.page)) {
			delete(o.pending, e.RequestID)
			o.mu.Unlock()
			o.send(xiaomiYoupinObserved{requestID: e.RequestID, failed: true})
			return
		}
		if ok {
			o.ready[e.RequestID] = true
		}
		o.mu.Unlock()
	case *network.EventLoadingFinished:
		o.mu.Lock()
		ok := o.pending[e.RequestID]
		ready := o.ready[e.RequestID]
		delete(o.pending, e.RequestID)
		delete(o.ready, e.RequestID)
		o.mu.Unlock()
		if ok {
			o.send(xiaomiYoupinObserved{requestID: e.RequestID, failed: !ready})
		}
	case *network.EventLoadingFailed:
		o.mu.Lock()
		ok := o.pending[e.RequestID]
		delete(o.pending, e.RequestID)
		delete(o.ready, e.RequestID)
		o.mu.Unlock()
		if ok {
			o.send(xiaomiYoupinObserved{requestID: e.RequestID, failed: true})
		}
	}
}

// Open the same product in a second tab of the user's existing browser context.
// The site's own frontend sends the gateway request; no POST or cookies are
// synthesized, copied, inspected, or written by the collector.
func (s *RenderedSession) captureXiaomiYoupin(ctx context.Context, page *url.URL, observedURL string) (Discovery, error) {
	result := Discovery{IsPage: true}
	id := xiaomiYoupinID(page)
	if err := ctx.Err(); err != nil {
		return result, err
	}
	observed, err := url.Parse(observedURL)
	if err != nil || id == "" || page.Scheme != "https" || !sameOrigin(page, observed) || xiaomiYoupinID(observed) != id {
		return result, errors.New("小米有品商品页面已更改")
	}
	checkCurrent := func() error {
		var state struct{ URL, Title string }
		if err := s.run(ctx, chromedp.Evaluate(`({URL:location.href,Title:document.title})`, &state)); err != nil {
			if ctx.Err() != nil {
				return ctx.Err()
			}
			return errors.New("小米有品当前页面不可用")
		}
		return xiaomiYoupinPageState(observedURL, state.URL, state.Title)
	}
	if err := checkCurrent(); err != nil {
		return result, err
	}
	child, closeChild, err := camoufox.NewPage(ctx, s.tab, false)
	if err != nil {
		return result, errors.New("无法创建小米有品采集标签")
	}
	defer closeChild()
	stop := context.AfterFunc(ctx, closeChild)
	defer stop()
	observer := newXiaomiYoupinObserver(page, child.Done())
	camoufox.ListenTarget(child, func(event any) {
		if paused, ok := event.(*fetch.EventRequestPaused); ok {
			allowed := false
			if paused.Request != nil && paused.Request.Method == "GET" && paused.RedirectedRequestID == "" {
				u, e := url.Parse(paused.Request.URL)
				allowed = e == nil && sameOrigin(page, u) && xiaomiYoupinID(u) == id
			}
			go func() {
				var action camoufox.Action = fetch.FailRequest(paused.RequestID, network.ErrorReasonBlockedByClient)
				if allowed {
					action = fetch.ContinueRequest(paused.RequestID)
				}
				_ = camoufox.Run(child, action)
			}()
			return
		}
		observer.event(event)
	})
	timer := time.AfterFunc(30*time.Second, closeChild)
	err = camoufox.Run(child, network.Enable().WithMaxResourceBufferSize(xiaomiYoupinMaxBody).WithMaxTotalBufferSize(4*xiaomiYoupinMaxBody).WithMaxPostDataSize(1), fetch.Enable().WithPatterns([]*fetch.RequestPattern{{ResourceType: network.ResourceTypeDocument}}))
	timer.Stop()
	if err != nil {
		if ctx.Err() != nil {
			return result, ctx.Err()
		}
		return result, errors.New("无法监听小米有品页面")
	}
	run := func(actions ...camoufox.Action) error {
		op, cancel := context.WithTimeout(child, 30*time.Second)
		defer cancel()
		err := camoufox.Run(op, actions...)
		if ctx.Err() != nil {
			return ctx.Err()
		}
		return err
	}
	target := page.Scheme + "://" + page.Host + "/detail?gid=" + url.QueryEscape(id)
	if err := run(camoufox.Navigate(target)); err != nil {
		if ctx.Err() != nil {
			return result, ctx.Err()
		}
		return result, errors.New("小米有品页面未加载，请在下载浏览器中完成登录或验证")
	}
	checkChild := func() error {
		var state struct{ URL, Title string }
		if err := run(chromedp.Evaluate(`({URL:location.href,Title:document.title})`, &state)); err != nil {
			if ctx.Err() != nil {
				return ctx.Err()
			}
			return errors.New("无法读取小米有品页面")
		}
		current, err := url.Parse(state.URL)
		if err != nil || !sameOrigin(page, current) || xiaomiYoupinID(current) != id {
			return errors.New("小米有品商品页面发生跳转，请完成登录或验证")
		}
		for _, word := range []string{"安全验证", "访问受限", "请登录"} {
			if strings.Contains(state.Title, word) {
				return errors.New("小米有品页面需要登录或安全验证，请在下载浏览器中完成")
			}
		}
		return nil
	}
	if err := checkChild(); err != nil {
		return result, err
	}
	deadline := time.NewTimer(15 * time.Second)
	defer deadline.Stop()
	for {
		select {
		case <-ctx.Done():
			return result, ctx.Err()
		case <-child.Done():
			if err := ctx.Err(); err != nil {
				return result, err
			}
			return result, errors.New("小米有品采集标签已关闭")
		case <-deadline.C:
			return result, errors.New("未捕获当前小米有品商品数据，请确认页面已加载或完成登录")
		case event := <-observer.events:
			if event.failed {
				continue
			}
			var body []byte
			err := run(chromedp.ActionFunc(func(c context.Context) error {
				var e error
				body, e = network.GetResponseBody(event.requestID).Do(c)
				return e
			}))
			if err != nil || len(body) > xiaomiYoupinMaxBody {
				continue
			}
			got, parseErr := xiaomiYoupinDetail(ctx, page, body)
			if len(got.Items) == 0 {
				continue
			}
			if err := checkCurrent(); err != nil {
				return result, err
			}
			if err := checkChild(); err != nil {
				return result, err
			}
			if observer.overflow.Load() && parseErr == nil {
				return got, errors.New("小米有品响应数量超过采集上限，已保留当前图片")
			}
			return got, parseErr
		}
	}
}
