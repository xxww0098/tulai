var mihuashiNumericID = regexp.MustCompile(`^[1-9][0-9]{0,19}$`)

func mihuashiProfileName(s string) bool {
	if s == "" || len(s) > 128 || !utf8.ValidString(s) || strings.TrimSpace(s) != s || s == "." || s == ".." || strings.ContainsAny(s, `/\\`) {
		return false
	}
	digits := true
	for _, r := range s {
		if unicode.IsControl(r) {
			return false
		}
		if r < '0' || r > '9' {
			digits = false
		}
	}
	return !digits || mihuashiNumericID.MatchString(s)
}

// shortcut: the site itself loads at most eight scrolls per capture; unvisited
// pages and unrecognized artwork remain explicitly marked as partial.
const (
	mihuashiMaxScrolls = 8
	mihuashiMaxBodies  = 100
	mihuashiMaxBody    = 4 << 20
	mihuashiMaxImages  = 1000
)

func mihuashiRef(u *url.URL) (kind, id string) {
	if !isMihuashiPage(u) || strings.Contains(strings.ToLower(u.EscapedPath()), "%2f") || strings.Contains(u.Path, "\\") {
		return "", ""
	}
	parts := strings.Split(strings.TrimSuffix(u.Path, "/"), "/")
	return parts[1], parts[2]
}

// Only the site's artwork storage is accepted; image URLs remain exactly as
// returned by the authorized page, including any site-provided query.
func mihuashiAsset(raw string) (string, bool) {
	if len(raw) == 0 || len(raw) > 8192 {
		return "", false
	}
	u, err := url.Parse(raw)
	if err != nil || u.User != nil || u.Scheme != "https" || !strings.EqualFold(u.Hostname(), "image-assets.mihuashi.com") ||
		(u.Port() != "" && u.Port() != "443") || u.Fragment != "" || strings.Contains(u.Path, "\\") || strings.Contains(u.Path, "..") ||
		strings.Contains(strings.ToLower(u.EscapedPath()), "%2f") ||
		(!strings.HasPrefix(u.Path, "/permanent/") && !strings.HasPrefix(u.Path, "/pfop/permanent/")) {
		return "", false
	}
	return u.String(), true
}

type mihuashiResponse struct {
	kind, owner string
	page        int
	requestID   network.RequestID
	failed      bool
}

// These are response shapes produced by the first-party page, not requests
// generated by the collector. A legacy /profiles URL is resolved by name.
func mihuashiAPI(raw string, origin *url.URL, routeKind, routeID string) (kind, owner string, page int) {
	if len(raw) == 0 || len(raw) > 8192 {
		return "", "", 0
	}
	u, err := url.Parse(raw)
	if err != nil || u.User != nil || u.Fragment != "" || u.Scheme != "https" || !sameOrigin(origin, u) ||
		strings.Contains(strings.ToLower(u.EscapedPath()), "%2f") || strings.Contains(u.Path, "\\") {
		return "", "", 0
	}
	parts := strings.Split(strings.Trim(u.Path, "/"), "/")
	if routeKind == "artworks" && len(parts) == 4 && parts[0] == "api" && parts[1] == "v1" && parts[2] == "artworks" && parts[3] == routeID {
		return "work", routeID, 0
	}
	if routeKind != "profiles" && routeKind != "users" {
		return "", "", 0
	}
	if len(parts) == 4 && parts[0] == "api" && parts[1] == "v1" && parts[2] == "users" && parts[3] == routeID {
		by := u.Query()["by"]
		want := "id"
		if routeKind == "profiles" {
			want = "name"
		}
		if len(by) == 1 && by[0] == want {
			return "user", routeID, 0
		}
	}
	if len(parts) == 5 && parts[0] == "api" && parts[1] == "v1" && parts[2] == "users" &&
		mihuashiNumericID.MatchString(parts[3]) && parts[4] == "artworks" {
		for _, name := range []string{"filter_tag_id", "filterTagId"} {
			for _, filter := range u.Query()[name] {
				if filter != "" && filter != "null" {
					return "", "", 0
				}
			}
		}
		values := u.Query()["page"]
		if len(values) != 1 {
			return "", "", 0
		}
		p, err := strconv.Atoi(values[0])
		if err == nil && p > 0 && p <= 100000 {
			return "list", parts[3], p
		}
	}
	return "", "", 0
}

func mihuashiUser(body []byte, routeKind, routeID string) (string, error) {
	var data struct {
		User struct {
			ID   json.Number `json:"id"`
			Name string      `json:"name"`
		} `json:"user"`
	}
	if len(body) == 0 || len(body) > mihuashiMaxBody || json.Unmarshal(body, &data) != nil || !mihuashiNumericID.MatchString(data.User.ID.String()) {
		return "", errors.New("米画师作者身份无法确认")
	}
	if (routeKind == "users" && data.User.ID.String() != routeID) || (routeKind == "profiles" && data.User.Name != routeID) {
		return "", errors.New("米画师作者身份不匹配")
	}
	return data.User.ID.String(), nil
}

type mihuashiArtwork struct {
	ID          json.Number `json:"id"`
	URL         string      `json:"url"`
	ArtworkType string      `json:"artwork_type"`
	CamelType   string      `json:"artworkType"`
}

func mihuashiImageItem(art mihuashiArtwork) (Item, bool) {
	asset, ok := mihuashiAsset(art.URL)
	artType := firstNonEmpty(art.ArtworkType, art.CamelType)
	if !ok || !mihuashiNumericID.MatchString(art.ID.String()) || (artType != "" && artType != "image") {
		return Item{}, false
	}
	return Item{URL: asset, Headers: map[string]string{"Referer": "https://www.mihuashi.com/"}, RequireImage: true, PublicOnly: true,
		Metadata: map[string]string{"mihuashi_artwork_id": art.ID.String()}}, true
}

func mihuashiWork(body []byte, id string) (Discovery, error) {
	result := Discovery{IsPage: true}
	var data struct {
		Artwork mihuashiArtwork `json:"artwork"`
	}
	if len(body) == 0 || len(body) > mihuashiMaxBody || json.Unmarshal(body, &data) != nil || data.Artwork.ID.String() != id {
		return result, errors.New("米画师作品身份无法确认")
	}
	item, ok := mihuashiImageItem(data.Artwork)
	if !ok {
		return result, errors.New("米画师作品图片不可用或无法确认")
	}
	result.Items = append(result.Items, item)
	return result, nil
}

func mihuashiList(ctx context.Context, body []byte, page int) (items []Item, total int, partial bool, err error) {
	if err := ctx.Err(); err != nil {
		return nil, 0, true, err
	}
	var data struct {
		Artworks   []json.RawMessage `json:"artworks"`
		TotalPages json.RawMessage   `json:"total_pages"`
	}
	if len(body) == 0 || len(body) > mihuashiMaxBody || json.Unmarshal(body, &data) != nil || data.Artworks == nil {
		return nil, -1, true, errors.New("米画师作品列表无法确认")
	}
	total = -1
	var reported *int
	if len(data.TotalPages) != 0 && json.Unmarshal(data.TotalPages, &reported) == nil && reported != nil &&
		*reported >= 0 && *reported <= 100000 && (page <= *reported || (*reported == 0 && len(data.Artworks) == 0 && page == 1)) {
		total = *reported
	} else {
		partial = true
	}
	if len(data.Artworks) > mihuashiMaxImages {
		data.Artworks = data.Artworks[:mihuashiMaxImages]
		partial = true
	}
	for _, raw := range data.Artworks {
		if err := ctx.Err(); err != nil {
			return items, total, true, err
		}
		var art mihuashiArtwork
		if json.Unmarshal(raw, &art) != nil {
			partial = true
			continue
		}
		item, ok := mihuashiImageItem(art)
		if !ok {
			partial = true
			continue
		}
		items = append(items, item)
	}
	return items, total, partial, nil
}

// These routes are recognized only to prevent generic scanning from saving
// logos, error illustrations or unrelated works when the site cannot load.
func isMihuashiPage(u *url.URL) bool {
	if u == nil || u.User != nil || (u.Scheme != "https" && u.Scheme != "http") ||
		(u.Port() != "" && !(u.Scheme == "https" && u.Port() == "443") && !(u.Scheme == "http" && u.Port() == "80")) {
		return false
	}
	host := strings.ToLower(u.Hostname())
	if host != "www.mihuashi.com" && host != "mihuashi.com" {
		return false
	}
	parts := strings.Split(strings.TrimSuffix(u.Path, "/"), "/")
	if len(parts) != 3 || (parts[1] != "profiles" && parts[1] != "users" && parts[1] != "artworks") {
		return false
	}
	if parts[1] == "profiles" {
		return mihuashiProfileName(parts[2])
	}
	return mihuashiNumericID.MatchString(parts[2])
}

func discoverMihuashi(ctx context.Context, getter Getter, page *url.URL) (Discovery, error) {
	result := Discovery{IsPage: true}
	if err := ctx.Err(); err != nil {
		return result, err
	}
	if getter == nil || !isMihuashiPage(page) {
		return result, errors.New("米画师页面地址或下载客户端无效")
	}
	return result, errors.New("米画师作品内容暂无法确认；作者接口需要站点验证，当前不支持采集")
}

func mihuashiPage(ctx context.Context, doc *html.Node, page *url.URL) (Discovery, error) {
	result := Discovery{IsPage: true}
	if err := ctx.Err(); err != nil {
		return result, err
	}
	if doc == nil || !isMihuashiPage(page) {
		return result, errors.New("米画师页面无效")
	}
	var title string
	walkHTML(doc, func(n *html.Node) {
		if n.Type == html.ElementNode && n.Data == "title" {
			title = strings.TrimSpace(nodeText(n))
		}
	})
	if err := ctx.Err(); err != nil {
		return result, err
	}
	switch {
	case strings.Contains(title, "服务器错误"):
		return result, errors.New("米画师页面显示服务器错误，作品内容暂无法确认")
	case strings.Contains(title, "安全验证"):
		return result, errors.New("米画师页面需要完成安全验证，作品内容暂无法确认")
	case strings.Contains(title, "登录"):
		return result, errors.New("米画师页面需要登录，作品内容暂无法确认")
	default:
		return result, errors.New("米画师作品内容暂无法确认，当前不支持采集")
	}
}

// captureMihuashi observes only the requests emitted by a second tab in the
// user's browser context. It never constructs the site's request signature.
func (s *RenderedSession) captureMihuashi(ctx context.Context, doc *html.Node, page *url.URL, observedURL string) (Discovery, error) {
	result := Discovery{IsPage: true}
	_, notice := mihuashiPage(ctx, doc, page)
	if ctx.Err() != nil {
		return result, ctx.Err()
	}
	if doc == nil {
		return result, notice
	}
	if notice != nil && (strings.Contains(notice.Error(), "服务器错误") || strings.Contains(notice.Error(), "安全验证") || strings.Contains(notice.Error(), "需要登录")) {
		return result, notice
	}
	kind, id := mihuashiRef(page)
	if kind == "" || page.Scheme != "https" {
		return result, errors.New("米画师网页身份无法确认")
	}
	checkCurrent := func() error {
		var raw string
		if err := s.run(ctx, chromedp.Location(&raw)); err != nil {
			if ctx.Err() != nil {
				return ctx.Err()
			}
			return errors.New("米画师原页面不可用")
		}
		current, err := url.Parse(raw)
		k, i := mihuashiRef(current)
		if err != nil || raw != observedURL || !sameOrigin(page, current) || k != kind || i != id {
			return errors.New("米画师页面已更改，已保留采集结果")
		}
		return nil
	}
	if err := checkCurrent(); err != nil {
		return result, err
	}
	child, closeChild, err := camoufox.NewPage(ctx, s.tab, false)
	if err != nil {
		return result, errors.New("无法创建米画师采集标签")
	}
	defer closeChild()
	stopOnCancel := context.AfterFunc(ctx, closeChild)
	defer stopOnCancel()
	run := func(actions ...camoufox.Action) error {
		op, cancel := context.WithTimeout(child, 30*time.Second)
		stop := context.AfterFunc(ctx, cancel)
		defer func() { stop(); cancel() }()
		if err := camoufox.Run(op, actions...); err != nil {
			if ctx.Err() != nil {
				return ctx.Err()
			}
			return err
		}
		return nil
	}
	events := make(chan mihuashiResponse, mihuashiMaxBodies)
	var mu sync.Mutex
	pending := make(map[network.RequestID]mihuashiResponse)
	ready := make(map[network.RequestID]bool)
	var count atomic.Int32
	var overflow atomic.Bool
	send := func(r mihuashiResponse) {
		select {
		case events <- r:
		case <-child.Done():
		default:
			overflow.Store(true)
		}
	}
	camoufox.ListenTarget(child, func(event any) {
		switch e := event.(type) {
		case *fetch.EventRequestPaused:
			allowed := false
			if e.Request != nil {
				target, err := url.Parse(e.Request.URL)
				k, i := mihuashiRef(target)
				allowed = e.Request.Method == "GET" && err == nil && sameOrigin(page, target) && k == kind && i == id
			}
			go func() {
				var action camoufox.Action = fetch.FailRequest(e.RequestID, network.ErrorReasonBlockedByClient)
				if allowed {
					action = fetch.ContinueRequest(e.RequestID)
				}
				_ = camoufox.Run(child, action)
			}()
		case *network.EventRequestWillBeSent:
			if e.RedirectResponse != nil {
				mu.Lock()
				request, ok := pending[e.RequestID]
				delete(pending, e.RequestID)
				delete(ready, e.RequestID)
				mu.Unlock()
				if ok {
					request.failed = true
					send(request)
				}
				return
			}
			if e.Request == nil || e.Request.Method != "GET" {
				return
			}
			requestKind, owner, p := mihuashiAPI(e.Request.URL, page, kind, id)
			if requestKind == "" {
				return
			}
			if count.Add(1) > mihuashiMaxBodies {
				overflow.Store(true)
				return
			}
			mu.Lock()
			pending[e.RequestID] = mihuashiResponse{kind: requestKind, owner: owner, page: p, requestID: e.RequestID}
			mu.Unlock()
		case *network.EventResponseReceived:
			mu.Lock()
			request, ok := pending[e.RequestID]
			if !ok {
				mu.Unlock()
				return
			}
			responseKind, owner, p := "", "", 0
			if e.Response != nil {
				responseKind, owner, p = mihuashiAPI(e.Response.URL, page, kind, id)
			}
			if e.Response == nil || e.Response.Status != 200 || e.Response.FromServiceWorker || responseKind != request.kind || owner != request.owner || p != request.page {
				delete(pending, e.RequestID)
				mu.Unlock()
				request.failed = true
				send(request)
				return
			}
			ready[e.RequestID] = true
			mu.Unlock()
		case *network.EventLoadingFinished:
			mu.Lock()
			request, ok := pending[e.RequestID]
			isReady := ready[e.RequestID]
			delete(pending, e.RequestID)
			delete(ready, e.RequestID)
			mu.Unlock()
			if ok {
				request.failed = !isReady
				send(request)
			}
		case *network.EventLoadingFailed:
			mu.Lock()
			request, ok := pending[e.RequestID]
			delete(pending, e.RequestID)
			delete(ready, e.RequestID)
			mu.Unlock()
			if ok {
				request.failed = true
				send(request)
			}
		}
	})
	initTimeout := time.AfterFunc(30*time.Second, closeChild)
	err = camoufox.Run(child, network.Enable().WithMaxResourceBufferSize(mihuashiMaxBody).WithMaxTotalBufferSize(4*mihuashiMaxBody).WithMaxPostDataSize(1),
		fetch.Enable().WithPatterns([]*fetch.RequestPattern{{ResourceType: network.ResourceTypeDocument}}))
	initTimeout.Stop()
	if err != nil {
		if ctx.Err() != nil {
			return result, ctx.Err()
		}
		return result, errors.New("无法监听米画师页面")
	}
	if err := run(camoufox.Navigate(page.String())); err != nil {
		if ctx.Err() != nil {
			return result, ctx.Err()
		}
		return result, errors.New("米画师页面未加载，请在下载浏览器中完成登录或验证")
	}
	var childRaw string
	if err := run(chromedp.Location(&childRaw)); err != nil {
		return result, errors.New("无法读取米画师页面")
	}
	current, err := url.Parse(childRaw)
	childKind, childID := mihuashiRef(current)
	if err != nil || !sameOrigin(page, current) || childKind != kind || childID != id {
		return result, errors.New("米画师页面发生跳转，请完成登录或验证")
	}
	var authorID string
	var incomplete, received bool
	var totalPages = -1
	waiting := make([]mihuashiResponse, 0)
	seenImages := make(map[string]bool)
	seenPages := make(map[int]bool)
	read := func(request mihuashiResponse) ([]byte, error) {
		var body []byte
		err := run(chromedp.ActionFunc(func(c context.Context) error {
			var e error
			body, e = network.GetResponseBody(request.requestID).Do(c)
			return e
		}))
		if err != nil || len(body) > mihuashiMaxBody {
			return nil, errors.New("米画师页面响应不可用")
		}
		return body, nil
	}
	processList := func(request mihuashiResponse) {
		if request.owner != authorID {
			return
		}
		if request.failed {
			incomplete = true
			return
		}
		body, err := read(request)
		if err != nil {
			incomplete = true
			return
		}
		items, total, partial, err := mihuashiList(ctx, body, request.page)
		if err != nil {
			incomplete = true
			return
		}
		received = true
		if partial {
			incomplete = true
		}
		if totalPages >= 0 && totalPages != total {
			incomplete = true
		}
		if totalPages < total {
			totalPages = total
		}
		seenPages[request.page] = true
		for _, item := range items {
			key := item.Metadata["mihuashi_artwork_id"]
			if seenImages[key] {
				continue
			}
			seenImages[key] = true
			if len(result.Items) >= mihuashiMaxImages {
				incomplete = true
				break
			}
			item.Metadata["mihuashi_author_id"] = authorID
			result.Items = append(result.Items, item)
		}
	}
	process := func(request mihuashiResponse) {
		switch request.kind {
		case "list":
			if authorID == "" {
				waiting = append(waiting, request)
			} else {
				processList(request)
			}
		case "user":
			if request.failed {
				incomplete = true
				return
			}
			body, err := read(request)
			if err != nil {
				incomplete = true
				return
			}
			user, err := mihuashiUser(body, kind, id)
			if err != nil || (authorID != "" && authorID != user) {
				incomplete = true
				return
			}
			authorID = user
			for _, pending := range waiting {
				processList(pending)
			}
			waiting = nil
		case "work":
			if request.failed {
				incomplete = true
				return
			}
			body, err := read(request)
			if err != nil {
				incomplete = true
				return
			}
			work, err := mihuashiWork(body, id)
			if err != nil {
				incomplete = true
				return
			}
			received = true
			result = work
		}
	}
	drain := func() error {
		idle := time.NewTimer(500 * time.Millisecond)
		defer idle.Stop()
		deadline := time.NewTimer(3 * time.Second)
		defer deadline.Stop()
		for {
			select {
			case <-ctx.Done():
				return ctx.Err()
			case <-child.Done():
				return errors.New("米画师采集标签已关闭")
			case request := <-events:
				process(request)
				if !idle.Stop() {
					select {
					case <-idle.C:
					default:
					}
				}
				idle.Reset(500 * time.Millisecond)
			case <-idle.C:
				return nil
			case <-deadline.C:
				return nil
			}
		}
	}
	for step := 0; step <= mihuashiMaxScrolls; step++ {
		if err := drain(); err != nil {
			return result, err
		}
		if err := checkCurrent(); err != nil {
			return result, err
		}
		if kind == "artworks" && received {
			break
		}
		if len(result.Items) >= mihuashiMaxImages {
			incomplete = true
			break
		}
		if step == mihuashiMaxScrolls {
			break
		}
		if err := run(chromedp.Evaluate(`window.scrollBy({top:window.innerHeight,behavior:"instant"})`, nil)); err != nil {
			if ctx.Err() != nil {
				return result, ctx.Err()
			}
			incomplete = true
			break
		}
	}
	if overflow.Load() || len(waiting) > 0 {
		incomplete = true
	}
	if kind != "artworks" && authorID == "" {
		return result, errors.New("米画师作者身份无法确认，请检查登录和页面状态")
	}
	if !received {
		return result, errors.New("米画师作品响应不可用，请检查登录和页面状态")
	}
	if kind == "artworks" {
		if incomplete {
			return result, errors.New("部分米画师作品响应无法读取，结果可能不完整")
		}
		return result, nil
	}
	if totalPages < 0 || (totalPages > 0 && len(seenPages) < totalPages) {
		incomplete = true
	}
	if incomplete {
		return result, errors.New("米画师仅采集已加载的可用作品，结果可能不完整")
	}
	return result, nil
}
