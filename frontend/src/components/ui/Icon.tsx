export interface IconProps {
  name: string;
  size?: number;
  strokeWidth?: number;
  className?: string;
  color?: string;
}

export function Icon({
  name,
  size = 14,
  strokeWidth = 1.85,
  className,
  color,
}: IconProps) {
  const Comp = ICON_MAP[name];
  if (!Comp) {
    return (
      <span
        aria-hidden="true"
        className={cn("inline-block shrink-0 rounded-sm bg-current/20", className)}
        style={{ width: size, height: size, color }}
      />
    );
  }
  return (
    <Comp
      size={size}
      strokeWidth={strokeWidth}
      color={color}
      aria-hidden="true"
      className={cn("shrink-0", className)}
    />
  );
}
